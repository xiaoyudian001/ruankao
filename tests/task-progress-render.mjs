import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const dir=path.resolve('outputs/chat-progress-render');fs.mkdirSync(dir,{recursive:true});
let code=fs.readFileSync('app/textbook/task-progress.tsx','utf8').replace("'../../lib/textbook/chat-recovery'",JSON.stringify(pathToFileURL(path.resolve('lib/textbook/chat-recovery.ts')).href));
const file=path.join(dir,'task-progress.mjs');fs.writeFileSync(file,ts.transpileModule(code,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {default:Progress}=await import(pathToFileURL(file).href);
const render=(props)=>renderToStaticMarkup(React.createElement(Progress,{clock:{server:180,local:Date.now()},connectionLost:false,computerOnline:true,...props}));
let html=render({job:{status:'queued',created_at:100,leased_at:null}});
assert.ok(html.includes('已排队'));assert.ok(html.includes('80 秒'));assert.ok(html.includes('无需重复发送'));
html=render({job:{status:'running',created_at:100,leased_at:110}});
assert.ok(html.includes('处理 70 秒'));assert.ok(html.includes('复杂问题'));assert.ok(!html.includes('正在重排'));
html=render({job:{status:'running',created_at:100,leased_at:110},connectionLost:true});
assert.ok(html.includes('暂时无法读取任务状态'));assert.ok(html.includes('继续读取同一任务'));
html=render({job:{status:'running',created_at:100,leased_at:110},computerOnline:false});
assert.ok(html.includes('电脑连接暂时中断'));assert.ok(!html.includes('暂时无法读取任务状态'));
console.log(JSON.stringify({passed:true,checks:['queue_elapsed','run_elapsed','slow_message','separate_network_and_desktop_state']}));
